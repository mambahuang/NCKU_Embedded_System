// 當 DMA 填滿前半部緩衝區時觸發 (Half Complete)
void HAL_I2S_RxHalfCpltCallback(I2S_HandleTypeDef *hi2s)
{
  if(hi2s->Instance == SPI2)
  {
    // 將前半部的 PDM 資料轉換為 PCM
    // 注意：ST 的 PDM_Filter 函式第一個參數通常吃 uint8_t*，所以要轉型
    PDM_Filter((uint8_t*)&PDM_Rx_Buffer[0],
               &PCM_Out_Buffer[0],
               &PDM1_filter_handler);

    // 設定旗標，通知主迴圈前半部資料準備好了
    pcm_data_ready = 1;
    pcm_half_or_full = 0;
  }
}

// 當 DMA 填滿後半部緩衝區時觸發 (Full Complete)
void HAL_I2S_RxCpltCallback(I2S_HandleTypeDef *hi2s)
{
  if(hi2s->Instance == SPI2)
  {
    // 將後半部的 PDM 資料轉換為 PCM
    PDM_Filter((uint8_t*)&PDM_Rx_Buffer[PDM_BUFFER_SIZE / 2],
               &PCM_Out_Buffer[PCM_BUFFER_SIZE / 2],
               &PDM1_filter_handler);

    // 設定旗標，通知主迴圈後半部資料準備好了
    pcm_data_ready = 1;
    pcm_half_or_full = 1;
  }
}
